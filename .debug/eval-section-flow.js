const out = { steps: [] }
const wait = ms => new Promise(r => setTimeout(r, ms))
const note = (k, v) => { out[k] = v }
const findNav = () => [...document.querySelectorAll('button')].filter(b => String(b.className).includes('navCell'))
const navTexts = () => findNav().map(b => (b.textContent || '').trim())
// 首次运行会有 Preview Notice，先关掉
const cont = [...document.querySelectorAll('[role="dialog"] button')].find(b => /continue/i.test(b.textContent || ''))
note('previewNotice', !!cont)
cont && cont.click(); await wait(500)
// 1) 展开侧栏、点齿轮
const openSidebar = document.querySelector('button[aria-label="Open sidebar"], button[aria-label="打开侧边栏"]')
if (openSidebar) { openSidebar.click(); await wait(650) }
note('workspaceRowsBefore', document.querySelectorAll('[data-row-key^="workspace:"]').length)
const gear = [...document.querySelectorAll('button')].find(b => (b.getAttribute('aria-label') || '') === 'Sidebar settings')
note('gearFound', !!gear)
gear && gear.click()
await wait(1900)
note('dialogOpen', !!document.querySelector('[role="dialog"]'))
note('navLabels', navTexts())
note('activeNav', findNav().filter(b => String(b.className).includes('active')).map(b => (b.textContent || '').trim()))
note('ourPageRendered', !!document.querySelector('.codex-sidebar-settings'))
const pick = el => { if (!el) return null; const cs = getComputedStyle(el); const r = el.getBoundingClientRect(); return { w: Math.round(r.width), h: Math.round(r.height), x: Math.round(r.x), y: Math.round(r.y), font: cs.fontSize + '/' + cs.fontWeight, color: cs.color, radius: cs.borderRadius, pad: cs.padding } }
note('card', pick(document.querySelector('.codex-sidebar-settings-card')))
note('intro', pick(document.querySelector('.codex-sidebar-settings-intro')))
note('switchBox', pick(document.querySelector('.codex-sidebar-switch')))
note('zoomRow', pick(document.querySelector('.codex-sidebar-settings-zoom-row')))
note('switches', [...document.querySelectorAll('.codex-sidebar-switch')].map(b => b.getAttribute('aria-checked')))
note('checkedWorkspaces', [...document.querySelectorAll('.codex-sidebar-settings-check[aria-checked="true"]')].map(b => (b.textContent || '').trim()))
note('zoomSteps', [...document.querySelectorAll('.codex-sidebar-zoom-step')].map(b => (b.textContent || '').trim() + (b.getAttribute('data-selected') === 'true' ? '*' : '')))
note('storedBefore', localStorage.getItem('dsh-codex-sidebar.settings'))
// 2) 打开日期视图
document.querySelectorAll('.codex-sidebar-switch')[0].click()
await wait(800)
note('dateModeOn', document.body.hasAttribute('data-codex-sidebar-date-view'))
note('dateHeadersOn', document.querySelectorAll('.codex-sidebar-date-header').length)
note('flatChildren', document.querySelectorAll('[data-row-key^="session:"]').length)
note('storedAfterDateOn', localStorage.getItem('dsh-codex-sidebar.settings'))
// 3) 关掉设置页，看侧栏
const closeBtn = [...document.querySelectorAll('[role="dialog"] button')].find(b => (b.textContent || '').trim() === 'Close')
note('closeFound', !!closeBtn)
closeBtn && closeBtn.click()
await wait(700)
note('dialogAfterClose', !!document.querySelector('[role="dialog"]'))
note('dateHeadersSidebar', document.querySelectorAll('.codex-sidebar-date-header').length)
note('workspaceRowsAfter', document.querySelectorAll('[data-row-key^="workspace:"]').length)
note('chips', document.querySelectorAll('.codex-sidebar-chip').length)
// 4) 设置页里改缩放
const gear2 = [...document.querySelectorAll('button')].find(b => (b.getAttribute('aria-label') || '') === 'Sidebar settings')
gear2 && gear2.click()
await wait(1600)
note('reopenActiveNav', findNav().filter(b => String(b.className).includes('active')).map(b => (b.textContent || '').trim()))
const step110 = [...document.querySelectorAll('.codex-sidebar-zoom-step')].find(b => (b.textContent || '').trim() === '110%')
step110 && step110.click()
await wait(400)
note('zoomAfter110', document.body.style.zoom)
note('zoomSelected', [...document.querySelectorAll('.codex-sidebar-zoom-step')].filter(b => b.getAttribute('data-selected') === 'true').map(b => b.textContent.trim()))
// 5) 复原：100% + 关日期视图 + 收起设置
const step100 = [...document.querySelectorAll('.codex-sidebar-zoom-step')].find(b => (b.textContent || '').trim() === '100%')
step100 && step100.click()
const dateSwitch = document.querySelectorAll('.codex-sidebar-switch')[0]
dateSwitch && dateSwitch.click()
await wait(700)
note('dateModeOff', document.body.hasAttribute('data-codex-sidebar-date-view'))
note('workspaceRowsRestored', document.querySelectorAll('[data-row-key^="workspace:"]').length)
note('storedFinal', localStorage.getItem('dsh-codex-sidebar.settings'))
out.steps.push('done')
return out